// packages/learning/src/eval/report.ts
//
// Report rendering for tl:eval: eval-report.json (full machine-readable
// output) + eval-report.md (human-readable summary with the promotion-gate
// verdicts and the student-vs-teacher comparison table).
//
// Eval reports are user/course data (AGENTS.md): they are written to the
// requested local directory only and are never uploaded anywhere.

import { mkdirSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import type { ComparisonTable, HarnessOutput, RunResult } from "./types"

const pct = (x: number): string => `${(x * 100).toFixed(1)}%`
const num = (x: number): string => (Number.isFinite(x) ? (Math.abs(x) >= 100 ? x.toFixed(1) : x.toFixed(4)) : String(x))
const bytes = (x: number): string => `${(x / 1024 / 1024).toFixed(1)} MiB`

const RUN_COL_WIDTH = 26

const table = (headers: string[], rows: string[][]): string => {
  const widths = headers.map((h, i) => Math.max(h.length, ...rows.map((r) => (r[i] ?? "").length)))
  const line = (cells: string[]) => cells.map((c, i) => (c ?? "").padEnd(widths[i]!).slice(0, widths[i]!)).join(" | ")
  const sep = widths.map((w) => "-".repeat(w)).join("-|-")
  return [line(headers), sep, ...rows.map(line)].join("\n")
}

const runMetricsRows = (run: RunResult): string[][] => {
  const m = run.metrics
  const kList = Object.keys(m.perRetriever.fused?.recallAtK ?? {}).map(Number).sort((a, b) => a - b)
  const rows: string[][] = [
    ["questions (in-book / off-topic)", `${m.inBookQuestions} / ${m.offTopicQuestions}`],
    ["gate precision", pct(m.gatePrecision)],
    ["gate recall (= off-topic refusal rate)", pct(m.gateRecall)],
    ["false-refusal rate (in-book)", pct(m.falseRefusalRate)],
    ["MRR (fused, uncapped)", num(m.mrr)],
    ["peak RSS", bytes(m.peakRssBytes)],
  ]
  for (const k of kList) {
    rows.push([
      `recall@${k} (bm25 / dense / fused)`,
      `${pct(m.perRetriever.bm25?.recallAtK[String(k)] ?? 0)} / ${pct(m.perRetriever.dense?.recallAtK[String(k)] ?? 0)} / ${pct(m.perRetriever.fused?.recallAtK[String(k)] ?? 0)}`,
    ])
  }
  rows.push(
    ["MRR@10 (bm25 / dense / fused)", `${num(m.perRetriever.bm25?.mrrAt10 ?? 0)} / ${num(m.perRetriever.dense?.mrrAt10 ?? 0)} / ${num(m.perRetriever.fused?.mrrAt10 ?? 0)}`],
    ["nDCG@10 (fused)", num(m.ndcgAt10)],
    [
      "latency p50 / p95 (embed + retrieve, ms)",
      `${num(m.latency.totalP50Ms)} / ${num(m.latency.totalP95Ms)} (embed ${num(m.latency.embedP50Ms)}/${num(m.latency.embedP95Ms)}, retrieve ${num(m.latency.retrieveP50Ms)}/${num(m.latency.retrieveP95Ms)})`,
    ],
    ["in-book bestDense p5 / off-topic p95", `${num(m.inBookBestDense.p5)} / ${num(m.offTopicBestDense.p95)}`],
    ["passed (correct gate + retrieval)", `${m.passed}/${m.totalQuestions}`],
  )
  return rows
}

const renderComparison = (c: ComparisonTable): string => {
  const lines: string[] = []
  const title =
    c.kind === "embedder"
      ? `### Encoder comparison — baseline "${c.baseline}" (teacher reference) vs the other embedder(s)`
      : "### Golden-set role comparison (student / teacher question sets)"
  lines.push(title, "")
  const headers = ["metric", ...c.columns.map((col) => col.run.slice(0, RUN_COL_WIDTH))]
  const rows = c.rows.map((r) => [
    r.metric,
    ...r.values.map((v) => String(v.value)),
  ])
  lines.push(table(headers, rows), "")
  if (c.falseRefusalDelta !== undefined) {
    lines.push(
      `False-refusal Δ (last run − baseline): ${num(c.falseRefusalDelta)} (plan §7 bound: 0.02)`,
      "",
    )
  }
  return lines.join("\n")
}

export const renderMarkdown = (out: HarnessOutput): string => {
  const lines: string[] = []
  lines.push(
    `# Targeted Learning eval report${out.config.tag ? ` — ${out.config.tag}` : ""}`,
    "",
    `- timestamp: ${out.timestamp}`,
    `- corpus: ${out.config.corpus}`,
    `- golden sets: ${out.config.goldenFiles.join(", ") || "(none)"}`,
    `- embedders: ${out.config.embedders.join(", ")}`,
    `- k: ${out.config.kList.join(", ")}`,
    `- gate thresholds: minDenseScore=${String(out.config.gate.minDenseScore)}, minFusedScore=${String(out.config.gate.minFusedScore)}`,
    "",
    "> Generated by `bun run tl:eval` (offline eval harness). Quality gates follow RETRIEVAL_V2_PLAN.md §7 / training/promote.py.",
    "",
  )

  for (const run of out.runs) {
    lines.push(
      `## Run: ${run.embedder}${run.role ? ` (role: ${run.role})` : ""}`,
      "",
      `Golden sets: ${run.goldenSets.join(", ")}`,
      "",
      table(["metric", "value"], runMetricsRows(run)),
      "",
    )
    const warnings = [...run.warnings]
    if (warnings.length > 0) {
      lines.push("Warnings:", ...warnings.map((w) => `- ${w}`), "")
    }
  }

  for (const c of out.comparisons) {
    lines.push(renderComparison(c))
  }

  lines.push("## Promotion gates (RETRIEVAL_V2_PLAN.md §7 / promote.py)", "")
  lines.push(
    table(
      ["gate", "semantics", "value", "floor", "verdict", "detail"],
      out.gates.checks.map((c) => [
        c.id,
        c.semantics,
        typeof c.value === "number" && c.id === "peak_rss" ? bytes(c.value) : num(c.value),
        c.floor === undefined ? "-" : c.id === "peak_rss" ? bytes(c.floor) : num(c.floor),
        c.verdict,
        c.detail,
      ]),
    ),
    "",
    `**Overall verdict: ${out.gates.overallVerdict}**`,
    "",
    "## HNSW decision hint (TODO §4)",
    "",
    `- recommendation: **${out.gates.hnsw.recommendation}** (p95 ${num(out.gates.hnsw.p95Ms)} ms vs ${out.gates.hnsw.targetMs} ms target)`,
    `- ${out.gates.hnsw.detail}`,
    "",
  )

  lines.push("## Per-question results", "")
  for (const run of out.runs) {
    lines.push(`### ${run.embedder}`, "")
    lines.push(
      table(
        ["question", "kind", "gate", "hit@fused", "ranks (bm25/dense/fused)", "bestDense", "bestFused", "ms"],
        run.rows.map((r) => [
          r.questionId,
          r.kind,
          r.gateDecision,
          r.hitAtK === undefined ? "-" : String(r.hitAtK),
          `${r.ranks.bm25 ?? "-"} / ${r.ranks.dense ?? "-"} / ${r.ranks.fused ?? "-"}`,
          num(r.bestDenseScore),
          num(r.bestFusedScore),
          num(r.embedMs + r.retrieveMs),
        ]),
      ),
      "",
    )
  }

  lines.push(
    "## Environment",
    "",
    ...Object.entries(out.environment).map(([k, v]) => `- ${k}: ${typeof v === "object" ? JSON.stringify(v) : String(v)}`),
    "",
  )
  return lines.join("\n")
}

export const writeReportFiles = (out: HarnessOutput, outDir: string, tag?: string): { json: string; markdown: string } => {
  mkdirSync(outDir, { recursive: true })
  const suffix = tag ? `-${tag.replace(/[^\w.-]+/g, "_")}` : ""
  const jsonPath = join(outDir, `eval-report${suffix}.json`)
  const mdPath = join(outDir, `eval-report${suffix}.md`)
  writeFileSync(jsonPath, `${JSON.stringify(out, null, 2)}\n`, "utf8")
  writeFileSync(mdPath, renderMarkdown(out), "utf8")
  return { json: jsonPath, markdown: mdPath }
}
