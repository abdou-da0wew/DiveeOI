// packages/learning/src/service.ts
//
// TargetedLearning.Service — the single Effect service that the HTTP API
// handlers consume. It composes the Setup state machine, the BooksStore,
// the manifest, and the probe, and exposes a coherent surface.
//
// Crucially, every method is total: BooksStore may be unavailable, and
// the service returns a structured BooksUnavailableError rather than
// crashing. The HTTP layer translates that into a 503 with a clear
// "library not found" message (plan §6.5).

import path from "node:path"
import { existsSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { Context, Effect, Layer, Schema } from "effect"
import { Global } from "@diveeoi/db/global"
import * as Setup from "./setup/state-machine"
import { Service as BooksStoreService, BooksStoreLayer, type BooksStoreInterface, BooksUnavailableError } from "./store"
import { probe, type ProbeResult } from "./probe"
import { type Manifest } from "./manifest/types"
import { PINNED_MANIFEST } from "./manifest/pinned"
import { setRuntime, modelDirFor } from "./runtime"

const __dirname = path.dirname(fileURLToPath(import.meta.url))

// ---------------------------------------------------------------------------
// Service interface
// ---------------------------------------------------------------------------

export interface TargetedLearningInterface {
  /** Data directory: <Global.Path.data>/targeted-learning */
  readonly dataDir: string
  /** Manifest, loaded lazily from manifest.json next to this package. */
  readonly manifest: Manifest | null
  /** Directory Transformers.js loads models from: <dataDir>/models. */
  readonly modelDir: string
  /** BooksStore service (may be in degraded mode). */
  readonly booksStore: BooksStoreInterface
  /** Setup state, re-read from disk on every call (cheap, single file). */
  getSetupState: () => Effect.Effect<Setup.SetupState, never>
  /** Run the probe. */
  runProbe: () => Effect.Effect<ProbeResult, never>
  /** Run a single setup step. */
  runStep: (
    name: Setup.StepName,
    stepFn: (state: Setup.SetupState) => Effect.Effect<unknown, unknown>,
    options?: { force?: boolean; signal?: AbortSignal },
  ) => Effect.Effect<Setup.SetupState, unknown>
  /** Reset for repair. */
  resetForRepair: () => Effect.Effect<Setup.SetupState, never>
  /** Mark any interrupted setup step pending so the pipeline can safely resume. */
  cancelSetup: () => Effect.Effect<Setup.SetupState, never>
  /** Boot-time quick health check. */
  bootCheck: () => Effect.Effect<{ healthy: boolean; missing: string[] }, never>
}

export class TargetedLearning extends Context.Service<TargetedLearning, TargetedLearningInterface>()("@diveeoi/learning/TargetedLearning") {}

// Backwards-compat alias. Use `TargetedLearning` everywhere.
export { TargetedLearning as Service }

// ---------------------------------------------------------------------------
// Manifest loader (cached, read once at layer construction)
// ---------------------------------------------------------------------------

const loadManifest = (): Manifest | null => {
  // The manifest.json sits next to this package's src/ — generated by
  // `bun run tl:manifest`. If missing, the service runs but Setup will
  // refuse to start the download step.
  const candidates = [
    path.join(__dirname, "..", "manifest.json"),
    path.join(__dirname, "..", "..", "manifest.json"),
    path.join(process.env.DIVEEOI_TL_MANIFEST ?? "", "manifest.json"),
  ]
  for (const candidate of candidates) {
    try {
      if (existsSync(candidate)) {
        const text = require("node:fs").readFileSync(candidate, "utf8")
        return JSON.parse(text) as Manifest
      }
    } catch {
      // try next
    }
  }
  return null
}

// ---------------------------------------------------------------------------
// Layer
// ---------------------------------------------------------------------------

const defaultDataDir = () => path.join(Global.Path.data, "targeted-learning")

export const layer = Layer.effect(
  TargetedLearning,
  Effect.gen(function* () {
    const dataDir = process.env.DIVEEOI_TL_DATA_DIR ?? defaultDataDir()
    const booksStore = yield* BooksStoreService
    // manifest.json next to the package wins (regenerated by tl:manifest); otherwise the
    // manifest compiled into the app. There is always a manifest, so Setup can always download.
    const manifest = loadManifest() ?? PINNED_MANIFEST
    setRuntime({ dataDir, modelDir: modelDirFor(dataDir), booksStore, manifest })

    if (booksStore.available && booksStore.db) {
      const ingest = yield* Effect.promise(() => import("./ingest/run"))
      yield* Effect.tryPromise({
        try: () => ingest.resumePersistedIngestJobs(booksStore.db!, dataDir),
        catch: (cause) => new Error("Failed to recover Targeted Learning ingest jobs", { cause }),
      }).pipe(
        Effect.tap((resumed) => Effect.logInfo("Targeted Learning ingest recovery complete", { resumed })),
        Effect.catchCause((cause) => Effect.logWarning("Targeted Learning ingest recovery failed", { cause })),
      )
    }

    return TargetedLearning.of({
      dataDir,
      modelDir: modelDirFor(dataDir),
      manifest,
      booksStore,
      getSetupState: () => Setup.loadState(dataDir),
      runProbe: () => probe(dataDir).pipe(Effect.orElseSucceed(() => ({}) as ProbeResult)),
      runStep: (name, stepFn, options) => Setup.runStep(dataDir, name, stepFn, options),
      resetForRepair: () => Setup.resetForRepair(dataDir),
      cancelSetup: () => Setup.cancelSetup(dataDir),
      bootCheck: () => Setup.bootCheck(dataDir),
    })
  }),
).pipe(Layer.provide(BooksStoreLayer))

// Convenience: layer that always serves "disabled".
export const disabledLayer = Layer.succeed(
  TargetedLearning,
  TargetedLearning.of({
    dataDir: "",
    modelDir: "",
    manifest: null,
    booksStore: { db: null, available: false, unavailabilityReason: "feature disabled" },
    getSetupState: () =>
      Effect.succeed({
        schemaVersion: 1,
        status: "not-started",
        steps: [],
        updatedAt: new Date().toISOString(),
      }),
    runProbe: () => Effect.succeed({} as ProbeResult),
    runStep: () => Effect.die("Targeted Learning disabled"),
    resetForRepair: () => Effect.succeed({} as Setup.SetupState),
    cancelSetup: () => Effect.succeed({} as Setup.SetupState),
    bootCheck: () => Effect.succeed({ healthy: false, missing: ["feature disabled"] }),
  }),
)

export { BooksUnavailableError, Schema }
